--
-- MIS → CSA status mapping:
--   IM  →  In Pay
--   OM  →  Not Eligible - Out of Pay
--   AS  →  Batch Sent - Application
--   CS  →  Batch Sent - Cancellation
--
-- Matching key: legacy_file_number (one contact per file number
--   confirmed by duplicate check in Step 1)
--
-- Fields updated: csa_status, din, icm_integration_status
--   icm_integration_status is set to TRUE so SYNC_ICM picks
--   up these records and pushes the changes back to ICM.
--
-- Steps:
--   1. Duplicate check   — confirm no file number maps to >1 contact
--   2. Pre-check         — confirm all file numbers are found (no NULLs)
--   3. UPDATE            — apply remediation inside a transaction
--   4. Post-check        — verify values landed correctly
--   5. Trigger SYNC_ICM  — POST /jobs/sync-icm (or node entrypoint)
--
-- DO NOT run Steps 3-5 if Steps 1-2 show unexpected results.
-- How to populate the VALUES block from the source CSV:
